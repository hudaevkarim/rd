/**
 * Очередь, выполняющая задачи строго по одной, в порядке добавления.
 *
 * ─── Зачем это нужно ──────────────────────────────────────────────────────────
 *
 * DataChannel доставляет кадры упорядоченно, и протокол на этом стоит: получатель
 * файла принимает чанк только если его `offset` совпал с ожидаемым, а Yjs
 * различает обновления по порядку. Но обработка кадра асинхронна — внутри
 * `crypto.subtle.decrypt`, — поэтому код вида
 *
 * ```ts
 * void aead.open(frame).then((opened) => emit(opened));
 * ```
 *
 * для нескольких кадров подряд отдаёт их наружу в порядке завершения
 * расшифровки, а не прихода. Дальше получатель файла отбрасывает чанк как
 * «перепрыгнувший» и просит докачку с места, куда отправитель ещё не дошёл.
 *
 * Параллельной расшифровки здесь сознательно нет: кадр файла — 16 КиБ, ctrl-кадр
 * Yjs — до мегабайта, и последовательная обработка упирается в скорость
 * расшифровки, а не в сеть. Окно передачи файла (256 КиБ) и так ограничивает
 * объём данных в полёте.
 *
 * Ошибка внутри задачи не должна рвать очередь: следующие кадры обязаны
 * обрабатываться, иначе один битый кадр навсегда остановил бы приём. Задача
 * сама решает, что делать с ошибкой (проверить, отбросить, разорвать соединение).
 */
export class SerialQueue {
  /** Хвост очереди: промис, который завершится после последней задачи. */
  #tail: Promise<void> = Promise.resolve();

  /** Глубина очереди — для диагностики в тестах. */
  #pending = 0;

  get pending(): number {
    return this.#pending;
  }

  push(task: () => Promise<void> | void): void {
    this.#pending++;
    // `.then(task, task)`: задача выполняется и после успеха, и после отказа
    // предыдущей — иначе одна ошибка навсегда остановила бы очередь.
    this.#tail = this.#tail.then(
      async () => {
        try {
          await task();
        } finally {
          this.#pending--;
        }
      },
      async () => {
        try {
          await task();
        } finally {
          this.#pending--;
        }
      },
    );
  }

  /** Выполняется после всех поставленных задач (или после закрытия очереди). */
  async drain(): Promise<void> {
    await this.#tail;
  }
}
