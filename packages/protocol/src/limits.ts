/**
 * Единые лимиты и номера версий протокола.
 *
 * Лимиты — это не «на всякий случай», а защита от DoS и от «раздутых» сообщений,
 * которые уронили бы слабый клиент. Значения подобраны так, чтобы Signaling-сервер
 * на 1 vCPU / 1 ГБ RAM не тратил CPU на парсинг мегабайтных SDP.
 */

/** Версия протокола. Повышается только при несовместимых изменениях. */
export const PROTOCOL_VERSION = 1;

/** Версия бинарного фрейма данных (первый байт кадра). */
export const FRAME_VERSION = 0x01;

/** Насколько дорогой PBKDF2 делать. OWASP рекомендует 600k итераций SHA-256 (2023). */
export const PBKDF2_ITERATIONS = 600_000;

/** Размер соли в байтах. Соль детерминирована от roomId, поэтому не нужно передавать в ссылке. */
export const ROOM_SALT_LEN = 32;

// ─── Комнаты ───────────────────────────────────────────────────────────────────

/**
 * Максимум участников в комнате.
 * Полная mesh-топология даёт n*(n-1)/2 RTCPeerConnection, поэтому на MVP
 * ограничиваемся 8: при 8 участниках это 28 соединений и 56 DataChannel —
 * вполне терпимо для слабых машин. Больше — уже нужен mesh-релей (SFU для данных).
 */
export const MAX_ROOM_PEERS = 8;

/** Комната перестаёт существовать, когда в ней 0 участников (сервер stateless — просто удаляем запись). */
export const ROOM_IDLE_EVICT_MS = 60_000;

// ─── Signaling (JSON поверх WSS) ───────────────────────────────────────────────

/** Максимальный размер входящего JSON-сообщения signaling. SDP бывает жирным, но не таким. */
export const MAX_SIGNAL_MESSAGE_BYTES = 96 * 1024;

/** Предельная длина SDP, которую мы готовы пробросить дальше. */
export const MAX_SDP_LEN = 64 * 1024;

/** Предельная длина сериализованного ICE-кандидата. */
export const MAX_CANDIDATE_LEN = 2 * 1024;

/** Имя участника в комнате. */
export const MAX_PEER_NAME_LEN = 40;

/** Имя файла книги. Заголовки Content-Disposition сюда не пишутся — только базовое имя. */
export const MAX_FILE_NAME_LEN = 200;

/** Длина сообщения в «быстром чате» комнаты. */
export const MAX_CHAT_LEN = 2_000;

// ─── P2P DataChannel ───────────────────────────────────────────────────────────

/** Полезная нагрузка одного чанка файла. 16 КиБ — безопасный компромисс. */
export const CHUNK_SIZE = 16 * 1024;

/** Максимальный размер кадра в канале файлов (с заголовками и AEAD-оверхедом). */
export const MAX_FILE_FRAME_BYTES = CHUNK_SIZE + 256;

/** Максимальный размер кадра в канале управления (Yjs-апдейты бывают крупными). */
export const MAX_CTRL_FRAME_BYTES = 1024 * 1024;

/**
 * Сколько байт AEAD добавляет к зашифрованному телу: nonce (12) + тег (16).
 * Нужен разборщику кадров, чтобы проверить длину чанка: в зашифрованном кадре
 * тело длиннее объявленного размера чанка ровно на эту величину.
 */
export const SEALED_OVERHEAD = 28;

/** Сколько сообщений "назад" принимаем в окне переигрывания. */
export const REPLAY_WINDOW = 64;

// ─── Лимиты rate limiting (сервер) ─────────────────────────────────────────────

/** Сообщений signaling в секунду на один IP. */
export const DEFAULT_RATE_PER_SEC = 20;

/** Сообщений signaling в минуту на один IP. */
export const DEFAULT_RATE_PER_MIN = 240;

/** Попыток открыть WebSocket-соединение в минуту на один IP. */
export const DEFAULT_CONNECT_PER_MIN = 30;

/** Задержка keepalive-пинга от сервера, мс. */
export const SERVER_PING_INTERVAL_MS = 20_000;
