/**
 * Выбор разбора книги по её содержимому.
 *
 * ─── Зачем нужен отдельный шаг ────────────────────────────────────────────────
 *
 * `parseEpub` и `parseFb2` возвращают одну и ту же структуру «главы → блоки»,
 * поэтому читать книгу дальше одинаково: якоря, прогресс, спойлеры и рендерер
 * не знают о формате. Различается только то, КАК достать блоки, а это
 * зависит от того, что мы держим в руках:
 *
 *   - **свою** книгу, выбранную пользователем: известно расширение и тип файла,
 *     но браузер для `.fb2` обычно присылает пустой MIME;
 *   - **чужую** книгу, полученную по P2P: имя файла может не доехать, а в
 *     `local-files.ts` расширение восстанавливается из каталога. Имя — тоже
 *     ненадёжный признак: участник мог переименовать файл при передаче.
 *
 * Поэтому решает содержимое: у FB2 корневой тег `FictionBook`, у EPUB — zip-
 * сигнатура. Ни то, ни другое нельзя угадать по расширению, а содержимое можно.
 *
 * Подсказка из каталога (`hint`) учитывается, но не решает: она приходит из
 * CRDT от другого участника, то есть это недоверенные данные. Если каталог
 * говорит «epub», а файл внутри — FB2, побеждает файл: иначе участник,
 * переименовавший книгу при передаче, не смог бы её открыть.
 */

import { Fb2Error, looksLikeFb2, parseEpub, parseFb2, type ParsedEpub } from '@rd/library';

export type TextFormat = 'epub' | 'fb2';

export interface ParsedTextBook {
  book: ParsedEpub;
  format: TextFormat;
}

/**
 * Разбирает книгу как EPUB или FB2 — по содержимому, с учётом подсказки.
 *
 * @param bytes содержимое файла целиком
 * @param hint формат из каталога комнаты; подсказка, а не приговор
 * @throws Fb2Error если содержимое — FB2, но разобрать его не удалось
 */
export function parseTextBook(bytes: Uint8Array, hint?: TextFormat): ParsedTextBook {
  const byContent = looksLikeFb2(bytes);
  // Каталог — недоверенная подсказка: он приезжает по общей CRDT и мог быть
  // переписан другим участником. Поэтому он умеет ТОЛЬКО уточнять, что файл
  // FB2, и никогда не переопределяет содержимое.
  const byHint = hint === 'fb2';
  if (!byContent && !byHint) return { book: parseEpub(bytes), format: 'epub' };
  if (byContent) {
    try {
      return { book: parseFb2(bytes), format: 'fb2' };
    } catch (error) {
      // Каталог говорил «epub», содержимое всё равно FB2: FB2 честнее, иначе
      // пользователь получил бы «битый zip» вместо внятной ошибки FB2.
      if (hint !== 'fb2') throw error;
    }
  }
  // Каталог говорил «fb2», а содержимое FB2 не содержит: пробуем EPUB. Ошибку
  // EPUB пользователю показывать правильнее, чем «ожидался FB2»: недоверенная
  // подсказка не должна превращать понятную ошибку в неверную.
  return { book: parseEpub(bytes), format: 'epub' };
}

/** MIME для книги: у FB2 его в природе нет, поэтому честно отдаём пустую строку. */
export function textMime(format: TextFormat, given: string): string {
  if (format === 'fb2') return given === '' ? 'application/x-fictionbook+xml' : given;
  return given === '' ? 'application/epub+zip' : given;
}

/** Список расширений для выбора файла. Держим рядом с разбором, чтобы не разъехалось. */
export const TEXT_ACCEPT = '.epub,.fb2,application/epub+zip,application/x-fictionbook+xml';